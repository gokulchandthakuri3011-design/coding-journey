/*
### Exercise 4: `while` Loop Practice
Use a `while` loop to print the following message 5 times:
```
Hello, Java learner!
*/

package Week1_Java_Basics.Day5_Loops;

public class Day5_Task4 {
    public static void main(String[] args) {
        // 'while' loop practice
        int a = 1;
        while(a <=5) {
            System.out.println("Hello, Java learner!");
            a++;
        }
    }
}
